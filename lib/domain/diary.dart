import 'dart:convert';

import '../core/time.dart';

/// A saved diary.
class Diary {
  const Diary({
    required this.id,
    required this.day,
    required this.title,
    required this.body,
    required this.bodyPlain,
    required this.createdAt,
    required this.updatedAt,
  });

  final String id;
  final Day day;
  final String title;

  /// Quill Delta JSON (see [DiaryBody]).
  final String body;
  final String bodyPlain;
  final int createdAt;
  final int updatedAt;
}

/// What the editor hands to the store when saving.
class DiaryInput {
  const DiaryInput({this.id, required this.day, required this.title, required this.body});

  /// null for a new diary.
  final String? id;
  final Day day;
  final String title;

  /// Quill Delta JSON.
  final String body;
}

/// The kinds of file a diary can embed. Ids are unique across kinds.
enum MediaKind {
  /// `<id>.jpg`.
  image('image', 'jpg', 'image/jpeg'),

  /// `<id>.mp4`. A video always comes with a cover: an image with an id of its own.
  video('video', 'mp4', 'video/mp4');

  const MediaKind(this.code, this.ext, this.mime);

  /// How the kind is stored in the database.
  final String code;
  final String ext;
  final String mime;

  static MediaKind of(String code) => code == video.code ? video : image;
}

/// Working with the stored body (a Quill Delta: a JSON list of insert operations) without the editor.
abstract final class DiaryBody {
  /// The embed type of a diary image. Its data is JSON: {"id": "...", "w": 960, "h": 720}.
  static const imageType = 'diary_image';

  /// The embed type of a diary video. Its data is JSON:
  /// {"id": "...", "cover": "...", "w": 960, "h": 720, "ms": 83000}.
  static const videoType = 'diary_video';

  /// An empty body (Quill documents always end with a newline).
  static const empty = '[{"insert":"\\n"}]';

  static List<dynamic> _ops(String body) {
    try {
      final decoded = jsonDecode(body);
      return decoded is List ? decoded : const [];
    } on FormatException {
      return const [];
    }
  }

  /// The text a person would read, for search: text inserts joined, images skipped, ends trimmed
  /// of the document's closing newline only.
  static String plainText(String body) {
    final buf = StringBuffer();
    for (final op in _ops(body)) {
      final insert = op is Map ? op['insert'] : null;
      if (insert is String) buf.write(insert);
    }
    final text = buf.toString();
    return text.endsWith('\n') ? text.substring(0, text.length - 1) : text;
  }

  /// Image ids referenced by the body: its images and the covers of its videos.
  static Set<String> imageIds(String body) {
    final ids = <String>{};
    for (final op in _ops(body)) {
      final insert = op is Map ? op['insert'] : null;
      if (insert is! Map) continue;
      if (insert[imageType] is String) {
        final ref = ImageRef.tryParse(insert[imageType] as String);
        if (ref != null) ids.add(ref.id);
      }
      if (insert[videoType] is String) {
        final ref = VideoRef.tryParse(insert[videoType] as String);
        if (ref != null) ids.add(ref.coverId);
      }
    }
    return ids;
  }

  /// Video ids referenced by the body.
  static Set<String> videoIds(String body) {
    final ids = <String>{};
    for (final op in _ops(body)) {
      final insert = op is Map ? op['insert'] : null;
      if (insert is Map && insert[videoType] is String) {
        final ref = VideoRef.tryParse(insert[videoType] as String);
        if (ref != null) ids.add(ref.id);
      }
    }
    return ids;
  }

  /// Every file id the body needs: images, video covers and videos.
  static Set<String> mediaIds(String body) => {...imageIds(body), ...videoIds(body)};

  static final _fileId = RegExp(r'^[A-Za-z0-9_-]{1,64}$');

  /// Whether [id] can name a file. Ids are generated by the app, but a body also arrives from the
  /// cloud and from import files, and an id becomes part of a file path.
  static bool isFileId(String id) => _fileId.hasMatch(id);

  /// Font families used in the body (Quill's font attribute), e.g. {'amdfont3'}.
  static Set<String> fontFamilies(String body) {
    final out = <String>{};
    for (final op in _ops(body)) {
      final attrs = op is Map ? op['attributes'] : null;
      if (attrs is Map && attrs['font'] is String) out.add(attrs['font'] as String);
    }
    return out;
  }

  /// Whether the body has anything in it (text other than whitespace, an image or a video).
  static bool hasContent(String body) => plainText(body).trim().isNotEmpty || mediaIds(body).isNotEmpty;
}

/// An image embedded in a diary: the file id and its stored pixel size.
class ImageRef {
  const ImageRef(this.id, this.width, this.height);

  final String id;
  final int width;
  final int height;

  String encode() => jsonEncode({'id': id, 'w': width, 'h': height});

  static ImageRef? tryParse(String data) {
    try {
      final m = jsonDecode(data);
      if (m is Map &&
          m['id'] is String &&
          m['w'] is int &&
          m['h'] is int &&
          (m['w'] as int) > 0 &&
          (m['h'] as int) > 0 &&
          DiaryBody.isFileId(m['id'] as String)) {
        return ImageRef(m['id'] as String, m['w'] as int, m['h'] as int);
      }
    } on FormatException {
      return null;
    }
    return null;
  }
}

/// A video embedded in a diary: the file id, its cover image's id, the stored pixel size (as shown,
/// upright) and its length.
class VideoRef {
  const VideoRef({required this.id, required this.coverId, required this.width, required this.height, required this.durationMs});

  final String id;

  /// The first frame, stored as an ordinary diary image.
  final String coverId;
  final int width;
  final int height;
  final int durationMs;

  String encode() => jsonEncode({'id': id, 'cover': coverId, 'w': width, 'h': height, 'ms': durationMs});

  static VideoRef? tryParse(String data) {
    try {
      final m = jsonDecode(data);
      if (m is Map &&
          m['id'] is String &&
          m['cover'] is String &&
          m['w'] is int &&
          m['h'] is int &&
          m['ms'] is int &&
          (m['w'] as int) > 0 &&
          (m['h'] as int) > 0 &&
          (m['ms'] as int) >= 0 &&
          DiaryBody.isFileId(m['id'] as String) &&
          DiaryBody.isFileId(m['cover'] as String)) {
        return VideoRef(
            id: m['id'] as String,
            coverId: m['cover'] as String,
            width: m['w'] as int,
            height: m['h'] as int,
            durationMs: m['ms'] as int);
      }
    } on FormatException {
      return null;
    }
    return null;
  }
}
